// Generates docs/en/shortcuts.md and docs/ru/shortcuts.md from the editor's own tables — never typed by hand:
// the commands (apps/web/src/actions/definitions.ts), both keymap presets (actions/keybindings/presets.ts) and the
// Russian names the app shows in its ⌘/ window (i18n/ru.ts).
//   WEB_SRC=apps/web/src bun assets/src/make-shortcuts.ts
import fs from "node:fs";
import path from "node:path";

const WEB = path.resolve(process.env.WEB_SRC || "apps/web/src");
const DOCS = path.join(import.meta.dir, "..", "..", "docs");
const { ACTIONS } = await import(path.join(WEB, "actions/definitions.ts"));
const { getPresetBindings } = await import(path.join(WEB, "actions/keybindings/presets.ts"));
const { RU } = await import(path.join(WEB, "i18n/ru.ts"));

const GLYPH: Record<string, string> = { mod: "⌘", cmd: "⌘", meta: "⌘", ctrl: "⌃", alt: "⌥", option: "⌥", shift: "⇧" };
const KEYNAME: Record<string, string> = { space: "Space", backspace: "⌫", delete: "⌦", enter: "↵", escape: "Esc", tab: "Tab", left: "←", right: "→", up: "↑", down: "↓", arrowleft: "←", arrowright: "→", arrowup: "↑", arrowdown: "↓", home: "Home", end: "End", pageup: "PgUp", pagedown: "PgDn", equal: "=", minus: "-", comma: ",", period: ".", slash: "/", backslash: "\\", semicolon: ";", quote: "'", backquote: "`" };
const ORDER = ["ctrl", "alt", "option", "shift", "mod", "cmd", "meta"];
function key(k: string): string {
	const parts = k.split("+").filter((x, i, a) => x !== "" || i === a.length - 1).map((x) => (x === "" ? "+" : x));
	const mods = parts.slice(0, -1).sort((a, b) => ORDER.indexOf(a) - ORDER.indexOf(b)).map((m) => GLYPH[m] ?? m);
	const last = parts.at(-1)!;
	const name = KEYNAME[last.toLowerCase()] ?? (last.length === 1 ? last.toUpperCase() : last.replace(/^f(\d+)$/i, "F$1"));
	return `<kbd>${[...mods, name].join("")}</kbd>`;
}
const esc = (s: string) => s.replace(/\|/g, "\\|");
const CATS: Record<string, [string, string]> = {
	playback: ["Playback", "Воспроизведение"],
	marks: ["Marks and markers", "Отметки и маркеры"],
	editing: ["Editing", "Монтаж"],
	timeline: ["Timeline and trimming", "Таймлайн и подрезка"],
	keyframes: ["Keyframes", "Ключевые кадры"],
	player: ["Player", "Плеер"],
	view: ["Windows and project", "Окна и проект"],
	assets: ["Media", "Медиа"],
};

function sheet(lang: "en" | "ru"): string {
	const by = (preset: string) => {
		// the app's own resolver: shared keyframe + lipsync keys, then the preset (its keys win)
		const m = new Map<string, string[]>();
		for (const [k, action] of getPresetBindings({ preset }) as Map<string, string>) m.set(action, [...(m.get(action) ?? []), k]);
		return m;
	};
	const cc = by("capcut");
	const fc = by("finalcut");
	const ru = lang === "ru";
	const out: string[] = [];
	out.push(ru ? "# Сочетания клавиш" : "# Keyboard shortcuts", "");
	out.push(ru
		? "> Этот лист собран скриптом `assets/src/make-shortcuts.ts` из таблиц самого редактора — команд и двух раскладок. Правьте не его, а исходники, и пересоберите."
		: "> Generated by `assets/src/make-shortcuts.ts` from the editor's own tables — the commands and both keymap presets. Do not edit by hand: change the source and regenerate.", "");
	out.push(ru
		? "Раскладка выбирается в **окне «Сочетания клавиш» (<kbd>⌘/</kbd>)**: «CapCut» (по умолчанию) или «Final Cut Pro». Там же любую клавишу можно переназначить и найти команду поиском. На Windows <kbd>⌘</kbd> — это <kbd>Ctrl</kbd>, <kbd>⌥</kbd> — <kbd>Alt</kbd>."
		: "Pick the keymap in **the Shortcuts window (<kbd>⌘/</kbd>)**: «CapCut» (default) or «Final Cut Pro». Any key can be rebound and any command searched there too. On Windows <kbd>⌘</kbd> is <kbd>Ctrl</kbd> and <kbd>⌥</kbd> is <kbd>Alt</kbd>.", "");
	const rows: Record<string, string[]> = {};
	let count = 0;
	for (const [id, def] of Object.entries(ACTIONS) as [string, { description: string; category: string; hidden?: boolean }][]) {
		if (def.hidden) continue;
		const a = cc.get(id) ?? [], b = fc.get(id) ?? [];
		if (!a.length && !b.length) continue;
		const name = ru ? (RU[def.description] ?? def.description) : def.description;
		(rows[def.category] ??= []).push(`| ${esc(name)} | ${a.map(key).join(" ") || "—"} | ${b.map(key).join(" ") || "—"} |`);
		count++;
	}
	for (const [cat, list] of Object.entries(rows)) {
		out.push(`## ${CATS[cat]?.[ru ? 1 : 0] ?? cat}`, "", ru ? "| Команда | CapCut | Final Cut Pro |" : "| Command | CapCut | Final Cut Pro |", "|---|---|---|", ...list, "");
	}
	out.push(ru ? `_${count} команд с клавишами._` : `_${count} commands with keys._`, "");
	return out.join("\n");
}
for (const lang of ["en", "ru"] as const) {
	fs.mkdirSync(path.join(DOCS, lang), { recursive: true });
	fs.writeFileSync(path.join(DOCS, lang, "shortcuts.md"), sheet(lang));
	// the manual's Keys page: the same sheet under the manual's heading
	fs.mkdirSync(path.join(DOCS, lang, "manual"), { recursive: true });
	fs.writeFileSync(path.join(DOCS, lang, "manual", "keys.md"), sheet(lang).replace(/^# .+$/m, lang === "ru" ? "# Клавиши\n\n[← Руководство](README.md)" : "# Keys\n\n[← Manual](README.md)"));
}
console.log("shortcuts written");
