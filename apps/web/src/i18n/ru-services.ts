/** A service's name as a sentence starts with it («The voice service» → «Сервис озвучки»; fal.ai stays). */
const who = (name: string) => {
	const own: Record<string, string> = { "The voice service": "Сервис озвучки", "The lipsync service": "Сервис липсинка", "The service": "Сервис" };
	return own[name] ?? RU_SERVICES[name] ?? name;
};
/** «Details: …» under a line, in Russian. */
const tail = (rest: string | undefined) => (rest ? rest.replace(/^\n\nDetails: /, "\n\nПодробности: ") : "");

