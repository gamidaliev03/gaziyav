#!/usr/bin/env node
// Packs open-source motion-design skills, as written by their authors, into src/montage/server/skills-github.ts
// for the AI Composition agent (loaded on demand, like an agent loads a skill).
//   SKILLS_SRC=<folder with the GitHub checkouts> node scripts/build-motion-skills.mjs
// Sources (checked out under SKILLS_SRC):
//   iart_<pack>/skills/<skill>/SKILL.md   — github.com/iart-ai/<pack> (MIT)
//   remotion-dev_skills/skills/…          — github.com/remotion-dev/skills (Remotion's skills for agents)
import fs from "node:fs";
import path from "node:path";

const SRC = process.env.SKILLS_SRC;
if (!SRC) throw new Error("SKILLS_SRC is required");
const OUT = path.join(import.meta.dirname, "..", "src", "montage", "server", "skills-github.ts");

const entries = [];
const strip = (md) => md.replace(/^---[\s\S]*?\n---\n/, "").trim();
const meta = (md, key) => (md.match(new RegExp(`^${key}:\\s*(.+)$`, "m"))?.[1] ?? "").trim();

for (const pack of fs.readdirSync(SRC).filter((d) => d.startsWith("iart_")).sort()) {
	const dir = path.join(SRC, pack, "skills");
	if (!fs.existsSync(dir)) continue;
	for (const skill of fs.readdirSync(dir).sort()) {
		const file = path.join(dir, skill, "SKILL.md");
		if (!fs.existsSync(file)) continue;
		const md = fs.readFileSync(file, "utf8");
		entries.push({
			id: meta(md, "name") || skill,
			source: `github.com/iart-ai/${pack.slice(5)} (MIT)`,
			description: meta(md, "description").replace(/^["']|["']$/g, ""),
			text: strip(md),
		});
	}
}

const remotion = path.join(SRC, "remotion-dev_skills", "skills", "remotion-best-practices");
for (const [id, rel] of [
	["remotion-best-practices", "SKILL.md"],
	["remotion-light-leaks", "remotion-markup/light-leaks.md"],
	["remotion-motion-blur", "remotion-markup/motion-blur.md"],
	["remotion-lottie", "remotion-markup/lottie.md"],
	["remotion-images", "remotion-markup/images.md"],
	["remotion-measuring-text", "remotion-markup/measuring-text.md"],
	["remotion-multi-scene-video", "remotion-markup/multi-scene-video.md"],
	["remotion-effects", "remotion-markup/effects.md"],
	["remotion-3d", "remotion-markup/3d.md"],
	["remotion-static-map", "remotion-maps/techniques/static-map/TECHNIQUE.md"],
]) {
	const file = path.join(remotion, rel);
	if (!fs.existsSync(file)) continue;
	const md = fs.readFileSync(file, "utf8");
	entries.push({ id, source: "github.com/remotion-dev/skills", description: meta(md, "description"), text: strip(md) });
}

const license = fs.readFileSync(path.join(SRC, "iart_motion-design-skills", "LICENSE"), "utf8").trim();
const body = `// Generated by scripts/build-motion-skills.mjs — do not edit by hand.
// Open-source motion-design skills as their authors wrote them, loaded on demand by the AI Composition agent.
// iart-ai motion skills: ${license.split("\n").slice(0, 3).join(" ").replace(/\s+/g, " ")} — full text in IART_LICENSE.
export interface GithubSkill {
	id: string;
	source: string;
	description: string;
	text: string;
}

export const IART_LICENSE = ${JSON.stringify(license)};

export const GITHUB_SKILLS: GithubSkill[] = ${JSON.stringify(entries, null, "\t")};
`;
fs.writeFileSync(OUT, body);
console.log(`${entries.length} skills, ${Math.round(body.length / 1024)} KB → ${path.relative(process.cwd(), OUT)}`);
